#!/usr/bin/env node
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(readFileSync(path.join(root, "manifest.json"), "utf8"));
const outfile = path.join(root, manifest.main ?? "extension.js");

await build({
  entryPoints: [path.join(root, "src", "index.js")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  charset: "utf8",
  legalComments: "none",
  minify: false,
  logLevel: "info",
  banner: {
    js: [
      `// ${manifest.name} ${manifest.version} - generated by build.mjs`,
      "// Source lives in src/; run npm run build after editing.",
    ].join("\n"),
  },
});
console.log(`[build] wrote ${path.basename(outfile)}`);
